class DepressionClassificationPipeline:

    def __init__(self, random_state=42):
        self.random_state = random_state
        self.models = {}

    def _tune(self, estimator, param_grid, X_scaled, y, cv, name):
        print(f"\n  Tuning {name}…")
        gs = GridSearchCV(estimator, param_grid, cv=cv,
                          scoring='f1_weighted', n_jobs=-1, verbose=0)
        gs.fit(X_scaled, y)
        print(f"    Best params : {gs.best_params_}")
        print(f"    Best CV F1  : {gs.best_score_:.4f}")
        return gs.best_estimator_

    def train(self, X_train_scaled, y_train, task='binary'):
        """Train and tune LR, RF, XGBoost; build soft-vote ensemble."""
        print(f"\n{'='*60}")
        print(f"TRAINING {task.upper()} MODELS")
        print("=" * 60)

        cv           = StratifiedKFold(n_splits=5, shuffle=True,
                                       random_state=self.random_state)
        class_weight = 'balanced'   # handles class imbalance for LR and RF

        # ── Logistic Regression ───────────────────────────────────────────────
        lr = self._tune(
            LogisticRegression(random_state=self.random_state, max_iter=1000,
                               solver='lbfgs', class_weight=class_weight),
            {'C': [0.01, 0.1, 1, 10], 'penalty': ['l2']},
            X_train_scaled, y_train, cv, "Logistic Regression"
        )

        # ── Random Forest ─────────────────────────────────────────────────────
        rf = self._tune(
            RandomForestClassifier(random_state=self.random_state, n_jobs=-1,
                                   class_weight=class_weight),
            {'n_estimators': [100, 200], 'max_depth': [5, 10, None],
             'min_samples_split': [2, 5]},
            X_train_scaled, y_train, cv, "Random Forest"
        )

        # ── XGBoost (FIXED) ───────────────────────────────────────────────────
        # Binary  : binary:logistic / logloss
        # Multiclass: multi:softprob (returns proba — required for soft voting)
        #             eval_metric: mlogloss (not 'logloss' which is for binary only)
        # Removed deprecated: use_label_encoder=False
        if task == 'binary':
            xgb_kwargs = {'objective': 'binary:logistic', 'eval_metric': 'logloss'}
        else:
            xgb_kwargs = {'objective': 'multi:softprob',  'eval_metric': 'mlogloss'}

        xgb = self._tune(
            XGBClassifier(random_state=self.random_state, n_jobs=-1,
                          verbosity=0, **xgb_kwargs),
            {'n_estimators': [100, 200], 'max_depth': [3, 5, 7],
             'learning_rate': [0.01, 0.1]},
            X_train_scaled, y_train, cv, "XGBoost"
        )

        # ── Soft-vote ensemble ────────────────────────────────────────────────
        print("\n  Building Voting Ensemble…")
        ensemble = VotingClassifier(
            estimators=[('lr', lr), ('rf', rf), ('xgb', xgb)],
            voting='soft'
        )
        ensemble.fit(X_train_scaled, y_train)

        models = {
            'logistic_regression': lr,
            'random_forest':       rf,
            'xgboost':             xgb,
            'voting_ensemble':     ensemble,
        }
        self.models[task] = models
        return models


