class FeatureImportanceAnalyzer:

    def __init__(self, bdi_cols, fcri_cols, feature_names):
        self.bdi_cols    = bdi_cols
        self.fcri_cols   = fcri_cols
        self.feat_names  = feature_names

    def extract(self, rf_model, xgb_model):
        rf_imp  = rf_model.feature_importances_
        xgb_imp = xgb_model.feature_importances_
        rf_norm  = rf_imp  / rf_imp.sum()
        xgb_norm = xgb_imp / xgb_imp.sum()
        df = pd.DataFrame({
            'feature':          self.feat_names,
            'rf_importance':    rf_norm,
            'xgb_importance':   xgb_norm,
            'combined':         (rf_norm + xgb_norm) / 2,
        }).sort_values('combined', ascending=False).reset_index(drop=True)
        return df

    def report_top(self, imp_df, top_n=5):
        print("\n" + "=" * 60)
        print("MOBILE APP OPTIMISATION — TOP PREDICTIVE ITEMS")
        print("=" * 60)
        top_bdi  = imp_df[imp_df['feature'].isin(self.bdi_cols)].head(top_n)
        top_fcri = imp_df[imp_df['feature'].isin(self.fcri_cols)].head(top_n)
        print(f"\nTop {top_n} BDI items:")
        for _, r in top_bdi.iterrows():
            print(f"  {r['feature']:8s}  {r['combined']:.4f}")
        print(f"\nTop {top_n} FCRI items:")
        for _, r in top_fcri.iterrows():
            feat = (r['feature'][:60] + '…') if len(r['feature']) > 60 else r['feature']
            print(f"  {feat:62s}  {r['combined']:.4f}")
        print("=" * 60)
        return {'top_bdi': top_bdi['feature'].tolist(),
                'top_fcri': top_fcri['feature'].tolist()}


