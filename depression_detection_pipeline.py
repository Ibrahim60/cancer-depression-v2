class TargetVariableEngineer:

    SEVERITY_BOUNDS = [
        ('Normal',                       0,  10),
        ('Mild mood disturbance',        11, 16),
        ('Borderline clinical depression',17, 20),
        ('Moderate depression',          21, 30),
        ('Severe depression',            31, 40),
        ('Extreme depression',           41, 63),
    ]
    SEVERITY_LABELS = [s[0] for s in SEVERITY_BOUNDS]

    def __init__(self, bdi_columns):
        self.bdi_columns = bdi_columns
        self.encoder = LabelEncoder()
        self.encoder.fit(self.SEVERITY_LABELS)

    def bdi_total(self, df):
        return df[self.bdi_columns].apply(pd.to_numeric, errors='coerce').sum(axis=1)

    def score_to_severity(self, score):
        if pd.isna(score):
            return 'Unknown'
        for label, lo, hi in self.SEVERITY_BOUNDS:
            if lo <= score <= hi:
                return label
        return 'Unknown'

    def create_targets(self, df):
        print("\n" + "=" * 60)
        print("TARGET VARIABLE ENGINEERING")
        print("=" * 60)
        df = df.copy()
        df['bdi_total']    = self.bdi_total(df)
        df['depression_severity']         = df['bdi_total'].apply(self.score_to_severity)
        df['depression_severity_encoded'] = self.encoder.transform(df['depression_severity'])
        df['has_depression']              = (df['bdi_total'] >= 11).astype(int)

        print(f"  BDI score  — mean {df['bdi_total'].mean():.1f}, "
              f"std {df['bdi_total'].std():.1f}, "
              f"range [{df['bdi_total'].min():.0f}, {df['bdi_total'].max():.0f}]")
        print(f"  Binary    : {df['has_depression'].value_counts().to_dict()}")
        print(f"  Multiclass: {df['depression_severity'].value_counts().to_dict()}")
        print("=" * 60)
        return df


