def main():
    print("\n" + "=" * 70)
    print("HYBRID ML FRAMEWORK FOR DEPRESSION DETECTION IN CANCER PATIENTS v2")
    print("=" * 70)

    # Ensure the output directory exists before any artifacts are saved.
    os.makedirs('models', exist_ok=True)

    data_path = os.path.join('Data', 'cancer_psychology.csv')

    print(f"\nLoading: {data_path}")
    df = pd.read_csv(data_path)
    print(f"Dataset : {df.shape[0]:,} rows × {df.shape[1]} columns")

    # 1. Preprocessing
    # Data treansormations
    preprocessor = ClinicalDataPreprocessor()
    df_proc, enc_features = preprocessor.fit_transform(df)

    # 2. Targets /labels
    # predactable values
    tve    = TargetVariableEngineer(preprocessor.bdi_columns)
    df_fin = tve.create_targets(df_proc)

    # 3. Feature matrix
    # List comphrisions
    feature_cols = [c for c in
                    preprocessor.bdi_columns + preprocessor.fcri_columns + enc_features
                    if c in df_fin.columns]
    X = df_fin[feature_cols].fillna(0)
    y_bin   = df_fin['has_depression']
    y_multi = df_fin['depression_severity_encoded']

    print(f"\nFeature matrix : {X.shape}")

    # 4. Single stratified split — shared by both binary and multiclass tasks
    #    (FIXED: v1 made two independent splits and the scaler was overwritten)
    X_train, X_test, y_bin_tr, y_bin_te = train_test_split(
        X, y_bin, test_size=0.2, random_state=RANDOM_STATE, stratify=y_bin)
    y_multi_tr = y_multi.loc[X_train.index]
    y_multi_te = y_multi.loc[X_test.index]

    # 5. Scaler — fit ONCE on training data, reuse for both tasks
    scaler         = StandardScaler()
    X_train_scaled = scaler.fit_transform(X_train)
    X_test_scaled  = scaler.transform(X_test)

    print(f"Train : {X_train.shape[0]:,}   Test : {X_test.shape[0]:,}")

    # 6. Training
    pipeline = DepressionClassificationPipeline(random_state=RANDOM_STATE)
    bin_models   = pipeline.train(X_train_scaled, y_bin_tr,   task='binary')
    multi_models = pipeline.train(X_train_scaled, y_multi_tr, task='multiclass')

    # 7. Feature importance
    analyzer   = FeatureImportanceAnalyzer(preprocessor.bdi_columns,
                                           preprocessor.fcri_columns,
                                           feature_cols)
    imp_df     = analyzer.extract(bin_models['random_forest'], bin_models['xgboost'])
    top_items  = analyzer.report_top(imp_df, top_n=5)
    imp_df.to_csv(os.path.join('models', 'feature_importance.csv'), index=False)

    # 8. Evaluation
    evaluator = ModelEvaluator(output_dir='models')

    bin_names    = ['No Depression', 'Has Depression']
    bin_results  = evaluator.evaluate(bin_models,   X_test_scaled, y_bin_te,   'binary',     bin_names)
    evaluator.plot_confusion(bin_models,   X_test_scaled, y_bin_te,   'binary',     bin_names)

    present_cls  = sorted(y_multi_te.unique())
    multi_names  = [tve.SEVERITY_LABELS[i] for i in present_cls]
    multi_results= evaluator.evaluate(multi_models, X_test_scaled, y_multi_te, 'multiclass', multi_names)
    evaluator.plot_confusion(multi_models, X_test_scaled, y_multi_te, 'multiclass', multi_names)

    # 9. Export (binary scaler saved; same scaler used for multiclass)
    evaluator.export(bin_models,   scaler, preprocessor, feature_cols, X_train, task='binary')
    evaluator.export(multi_models, scaler, preprocessor, feature_cols, X_train, task='multiclass')

    # 10. Summary
    best_bin   = max(bin_results,   key=lambda x: bin_results[x]['f1'])
    best_multi = max(multi_results, key=lambda x: multi_results[x]['f1'])
    print("\n" + "=" * 70)
    print("COMPLETE")
    print("=" * 70)
    print(f"Best binary model     : {best_bin}  (F1={bin_results[best_bin]['f1']:.4f})")
    print(f"Best multiclass model : {best_multi}  (F1={multi_results[best_multi]['f1']:.4f})")
    print(f"Top BDI  items (mobile): {top_items['top_bdi']}")
    print(f"Top FCRI items (mobile): {top_items['top_fcri']}")
    print(f"Artifacts saved to    : models/")
    print("=" * 70)

    return {
        'binary_models':   bin_models,
        'multi_models':    multi_models,
        'feature_cols':    feature_cols,
        'feature_imp':     imp_df,
        'top_items':       top_items,
        'preprocessor':    preprocessor,
        'target_engineer': tve,
        'scaler':          scaler,
    }


if __name__ == '__main__':
    results = main()