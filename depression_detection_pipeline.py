class ClinicalDataPreprocessor:
    """Comprehensive data preprocessing for clinical psychometric data.

    Supports two column-naming conventions:
      • Legacy CSV   : BDI items named '1.' … '21.', FCRI items start with 'N. '
      • Clean/v2     : BDI items named 'BDI_1' … 'BDI_21', FCRI 'FCRI_1' … 'FCRI_42'
    Supports two response formats:
      • Text string  : 'I feel sad', 'Somewhat', 'A few times a week', …
      • Digit-prefix : '1 - I feel sad', '2 - Somewhat', …  (v2 Google Forms output)
      • Plain integer: 0, 1, 2, 3, 4  (generated by mock data or pre-processed)
    """

    FCRI_SUBSCALES = {
        'triggers':               list(range(1, 9)),
        'severity':               list(range(9, 18)),   # item 13 reversed before summing
        'psychological_distress': list(range(18, 22)),
        'functioning_impairments':list(range(22, 28)),
        'insight':                list(range(28, 31)),
        'reassurance':            list(range(31, 34)),
        'coping_strategies':      list(range(34, 43)),
    }

    # ── Fixed FCRI text → integer mappings ───────────────────────────────────
    # Key bugs fixed:
    #   item 15: 'a few times a month'→1 (was 2), 'a few times a week'→2 (was 3),
    #            'several times a day'→4 (was missing), removed 'a few times a year'/'at least once a day'
    #   item 17: 'several years'→4 (was 'since my diagnosis' which doesn't exist in data)
    FCRI_SCORE_MAP = {
        # Frequency scale (Triggers, Reassurance, Coping, Reassurance Effectiveness)
        'never': 0, 'rarely': 1, 'sometimes': 2, 'most of the time': 3, 'all the time': 4,
        # Intensity scale (Severity 9-13, Distress, Functioning, Insight)
        'not at all': 0, 'a little': 1, 'somewhat': 2, 'a lot': 3, 'a great deal': 4,
        # Item 14 — risk perception
        'not at all at risk': 0, 'a little at risk': 1, 'somewhat at risk': 2,
        'a lot at risk': 3, 'a great deal at risk': 4,
        # Item 15 — frequency (FIXED: correct 0-4 order)
        'a few times a month': 1, 'a few times a week': 2,
        'a few times a day': 3, 'several times a day': 4,
        # Item 16 — time per day
        "i don't think about it": 0, 'a few seconds': 1, 'a few minutes': 2,
        'a few hours': 3, 'several hours': 4,
        # Item 17 — duration (FIXED: 'several years' not 'since my diagnosis')
        'a few weeks': 1, 'a few months': 2, 'a few years': 3, 'several years': 4,
    }

    def __init__(self):
        self.bdi_columns  = []
        self.fcri_columns = []
        self.demographic_columns = {}
        self.label_encoders = {}

    # ── Column identification ─────────────────────────────────────────────────

    def _identify_columns(self, df):
        cols = df.columns.tolist()

        # BDI: legacy '1.'…'21.' OR clean 'BDI_1'…'BDI_21'
        legacy_bdi = {f'{i}.' for i in range(1, 22)}
        clean_bdi  = {f'BDI_{i}' for i in range(1, 22)}
        self.bdi_columns = [c for c in cols
                            if c.strip() in legacy_bdi or c.strip() in clean_bdi]

        # FCRI: legacy 'N. <text>' OR clean 'FCRI_N'
        clean_fcri = {f'FCRI_{i}' for i in range(1, 43)}
        self.fcri_columns = []
        for c in cols:
            cs = c.strip()
            if cs in clean_fcri:
                self.fcri_columns.append(c)
                continue
            for n in range(1, 43):
                if cs.startswith(f'{n}. ') and len(cs) > len(f'{n}. ') + 3:
                    self.fcri_columns.append(c)
                    break

        # Demographic columns — updated for both legacy and v2 field names
        self.demographic_columns = {
            'gender':            self._find_col(cols, ['gender']),
            'age_group':         self._find_col(cols, ['age group', 'age_group']),
            'province':          self._find_col(cols, ['province', 'povince']),
            'cancer_type':       self._find_col(cols, ['cancer type', 'cancer_type']),
            'cancer_stage':      self._find_col(cols, ['cancer stage', 'cancer_stage']),        # v2
            'treatment_type':    self._find_col(cols, ['treatment type', 'current treatment']),
            'cancer_status':     self._find_col(cols, ['cancer status']),
            'collection_site':   self._find_col(cols, ['collection site', 'data collection']),  # v2
            'education_level':   self._find_col(cols, ['education level', 'education_level']),  # v2
            'marital_status':    self._find_col(cols, ['marital status', 'marital_status']),    # v2
            'employment_status': self._find_col(cols, ['employment status', 'employment_status']),# v2
            'prior_psych':       self._find_col(cols, ['prior psych', 'prior_psych']),          # v2
            'on_medication':     self._find_col(cols, ['medication for depression',
                                                        'on_psych_medication',
                                                        'taking any medication']),
            'diagnosis_duration':self._find_col(cols, ['duration since diagnosis',
                                                        'duration_since_diagnosis']),
        }

        n_found_demo = sum(1 for v in self.demographic_columns.values() if v is not None)
        print(f"  BDI columns  : {len(self.bdi_columns)}")
        print(f"  FCRI columns : {len(self.fcri_columns)}")
        print(f"  Demo columns : {n_found_demo}/{len(self.demographic_columns)} found")

    def _find_col(self, cols, terms):
        for c in cols:
            for t in terms:
                if t.lower() in c.lower().strip():
                    return c
        return None

    # ── Numeric conversion ────────────────────────────────────────────────────

    def _parse_bdi(self, val) -> float:
        """Convert any BDI response format to 0-3 integer."""
        if pd.isna(val):
            return np.nan
        s = str(val).strip().lower().rstrip('.')

        # Already numeric (mock data or pre-processed)
        try:
            v = float(s)
            if v in (0, 1, 2, 3):
                return int(v)
        except ValueError:
            pass

        # v2 digit-prefix format: '2 - I am sad all the time...'
        if re.match(r'^[0-3] - ', s):
            try:
                return int(s[0])
            except ValueError:
                pass

        # Keyword matching for legacy text format (ordered highest→lowest severity)
        keywords = {
            3: ['so sad and unhappy', 'future is hopeless', 'complete failure',
                'dissatisfied or bored', 'guilty all of the time', 'i am being punished',
                'hate myself', 'blame myself for everything', 'would kill myself if i had',
                "can't cry even though", 'irritated all the time', 'lost all of my interest',
                "can't make decisions at all", 'look ugly', "can't do any work",
                'several hours earlier', 'too tired to do anything', 'no appetite at all',
                'lost more than fifteen', 'so worried about my physical',
                'lost interest in sex completely'],
            2: ['sad all the time', 'nothing to look forward', 'lot of failures',
                "don't get real satisfaction", 'quite guilty most', 'expect to be punished',
                'disgusted with myself', 'blame myself all the time', 'would like to kill myself',
                'cry all the time', 'quite annoyed', 'lost most of my interest',
                'greater difficulty in making', 'permanent changes in my appearance',
                'push myself very hard', '1-2 hours earlier', 'tired from doing almost',
                'appetite is much worse', 'lost more than ten', 'very worried about physical',
                'almost no interest in sex'],
            1: ['i feel sad', 'feel discouraged', 'failed more than',
                "don't enjoy things", 'guilty a good part', 'may be punished',
                'disappointed in myself', 'critical of myself',
                'thoughts of killing myself, but', 'cry more now than',
                'slightly more irritated', 'less interested in other people',
                'put off making decisions', 'worried that i am looking',
                'extra effort to get started', "don't sleep as well",
                'get tired more easily', 'appetite is not as good', 'lost more than five',
                'worried about physical problems', 'less interested in sex than'],
        }
        for score in (3, 2, 1):
            if any(kw in s for kw in keywords[score]):
                return score
        return 0  # default to 0 if no keyword match

    def _parse_fcri(self, val) -> float:
        """Convert any FCRI response format to 0-4 integer."""
        if pd.isna(val):
            return np.nan
        s = str(val).strip()

        # Already numeric
        try:
            v = float(s)
            if 0 <= v <= 4:
                return int(v)
        except ValueError:
            pass

        # v2 digit-prefix: '0 - Not at all'
        if re.match(r'^[0-4] - ', s):
            try:
                return int(s[0])
            except ValueError:
                pass

        # Text lookup
        return self.FCRI_SCORE_MAP.get(s.lower(), np.nan)

    def _convert_to_numeric(self, df):
        df = df.copy()
        for col in self.bdi_columns:
            if col in df.columns:
                df[col] = df[col].apply(self._parse_bdi)
        for col in self.fcri_columns:
            if col in df.columns:
                df[col] = df[col].apply(self._parse_fcri)
        return df

    # ── FCRI item 13 reversal ─────────────────────────────────────────────────

    def _reverse_fcri_item_13(self, df):
        """Reverse-score FCRI item 13 (I believe I am cured). reversed = 4 − raw."""
        for col in self.fcri_columns:
            cs = col.strip()
            # Matches legacy '13. I believe...' or clean 'FCRI_13'
            if cs == 'FCRI_13' or cs.startswith('13. '):
                df = df.copy()
                df[col] = pd.to_numeric(df[col], errors='coerce')
                df[col] = 4 - df[col]
                print("  Reversed FCRI item 13")
                break
        return df

    # ── Quality filters ───────────────────────────────────────────────────────

    def _drop_mechanical(self, df):
        if not self.fcri_columns:
            return df
        mask = (df[self.fcri_columns] == 0).all(axis=1)
        n = mask.sum()
        if n:
            print(f"  Dropped {n} mechanical-response rows (all FCRI = 0)")
            df = df[~mask].reset_index(drop=True)
        return df

    def _drop_excessive_missing(self, df, threshold=0.5):
        q_cols  = self.bdi_columns + self.fcri_columns
        pct_nan = df[q_cols].isna().mean(axis=1)
        mask    = pct_nan > threshold
        n = mask.sum()
        if n:
            print(f"  Dropped {n} rows with >{threshold*100:.0f}% missing questionnaire items")
            df = df[~mask].reset_index(drop=True)
        return df

    # ── Subscale-mean imputation ──────────────────────────────────────────────

    def _get_subscale_cols(self, subscale_name):
        nums = self.FCRI_SUBSCALES[subscale_name]
        candidates_legacy = {f'{n}.' for n in nums} | {f'{n} ' for n in nums}
        candidates_clean  = {f'FCRI_{n}' for n in nums}
        result = []
        for col in self.fcri_columns:
            cs = col.strip()
            if cs in candidates_clean:
                result.append(col)
            else:
                for n in nums:
                    if cs.startswith(f'{n}. ') or cs.startswith(f'{n}.'):
                        result.append(col)
                        break
        return result

    def _impute_subscale_means(self, df):
        df = df.copy()
        for col in self.bdi_columns + self.fcri_columns:
            if col in df.columns:
                df[col] = pd.to_numeric(df[col], errors='coerce')

        # BDI: impute with patient's own BDI mean
        if self.bdi_columns:
            bdi_means = df[self.bdi_columns].astype(float).mean(axis=1)
            for col in self.bdi_columns:
                mask = df[col].isna()
                if mask.any():
                    df.loc[mask, col] = bdi_means[mask].round()

        # FCRI: impute with patient's own subscale mean
        for sub in self.FCRI_SUBSCALES:
            sub_cols = [c for c in self._get_subscale_cols(sub) if c in df.columns]
            if not sub_cols:
                continue
            sub_means = df[sub_cols].astype(float).mean(axis=1)
            for col in sub_cols:
                mask = df[col].isna()
                if mask.any():
                    df.loc[mask, col] = sub_means[mask].round()
        return df

    # ── Categorical encoding ──────────────────────────────────────────────────

    def _encode_categoricals(self, df):
        df = df.copy()
        encoded = []
        for name, col in self.demographic_columns.items():
            if col is None or col not in df.columns:
                continue
            df[col] = df[col].fillna('Unknown').astype(str).str.strip()
            le = LabelEncoder()
            enc_col = f'{name}_encoded'
            df[enc_col] = le.fit_transform(df[col])
            self.label_encoders[name] = le
            encoded.append(enc_col)
        return df, encoded

    # ── Master pipeline ───────────────────────────────────────────────────────

    def fit_transform(self, df):
        print("=" * 60)
        print("DATA PREPROCESSING")
        print("=" * 60)
        df_out = df.copy()
        n_in   = len(df_out)
        print(f"  Input rows: {n_in:,}")

        self._identify_columns(df_out)

        # Drop PII
        for col in ['Name', 'Timestamp', 'Patient Code / ID', 'Patient_ID']:
            if col in df_out.columns:
                df_out = df_out.drop(columns=[col])

        df_out = self._convert_to_numeric(df_out)

        # Conversion quality check
        if self.bdi_columns:
            ok = df_out[self.bdi_columns].notna().mean().mean()
            print(f"  BDI conversion rate : {ok*100:.1f}%")
            if ok < 0.80:
                print("  WARNING: BDI conversion rate below 80% — check response text formats.")
        if self.fcri_columns:
            ok = df_out[self.fcri_columns].notna().mean().mean()
            print(f"  FCRI conversion rate: {ok*100:.1f}%")
            if ok < 0.80:
                print("  WARNING: FCRI conversion rate below 80% — check response text formats.")

        df_out = self._reverse_fcri_item_13(df_out)
        df_out = self._drop_mechanical(df_out)
        df_out = self._drop_excessive_missing(df_out)
        df_out = self._impute_subscale_means(df_out)
        df_out, enc_features = self._encode_categoricals(df_out)

        print(f"  Output rows : {len(df_out):,}  (dropped {n_in - len(df_out):,})")
        print("=" * 60)
        return df_out, enc_features


