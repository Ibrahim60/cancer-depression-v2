class ModelEvaluator:

    def __init__(self, output_dir='models'):
        self.output_dir = output_dir
        os.makedirs(output_dir, exist_ok=True)

    def evaluate(self, models, X_test_scaled, y_test, task='binary', class_names=None):
        """Accuracy / Precision / Recall / F1 / ROC-AUC for every model."""
        print(f"\n{'='*60}")
        print(f"{task.upper()} EVALUATION")
        print("=" * 60)
        results = {}

        for name, model in models.items():
            y_pred = model.predict(X_test_scaled)
            res = {
                'accuracy' : accuracy_score(y_test, y_pred),
                'precision': precision_score(y_test, y_pred, average='weighted', zero_division=0),
                'recall'   : recall_score(y_test, y_pred, average='weighted', zero_division=0),
                'f1'       : f1_score(y_test, y_pred, average='weighted', zero_division=0),
            }

            # ROC-AUC (binary: standard; multiclass: macro OvR)
            if hasattr(model, 'predict_proba'):
                try:
                    y_proba = model.predict_proba(X_test_scaled)
                    if task == 'binary':
                        res['roc_auc'] = roc_auc_score(y_test, y_proba[:, 1])
                    else:
                        res['roc_auc'] = roc_auc_score(
                            y_test, y_proba, multi_class='ovr', average='macro')
                except Exception:
                    res['roc_auc'] = None
            else:
                res['roc_auc'] = None

            results[name] = res
            print(f"\n  {name.upper()}")
            print(f"  Accuracy  {res['accuracy']:.4f}  Precision {res['precision']:.4f}  "
                  f"Recall {res['recall']:.4f}  F1 {res['f1']:.4f}")
            if res['roc_auc'] is not None:
                print(f"  ROC-AUC   {res['roc_auc']:.4f}")
            if class_names:
                print(classification_report(y_test, y_pred,
                                            target_names=class_names, zero_division=0))

        return results

    def plot_confusion(self, models, X_test_scaled, y_test, task, class_names=None):
        n = len(models)
        fig, axes = plt.subplots(1, n, figsize=(5 * n, 4))
        if n == 1:
            axes = [axes]
        for ax, (name, model) in zip(axes, models.items()):
            y_pred = model.predict(X_test_scaled)
            ConfusionMatrixDisplay(confusion_matrix(y_test, y_pred),
                                   display_labels=class_names).plot(
                ax=ax, cmap='Blues', colorbar=False)
            ax.set_title(name)
        plt.tight_layout()
        path = os.path.join(self.output_dir, f'{task}_confusion.png')
        plt.savefig(path, dpi=150)
        plt.close()
        print(f"  Confusion matrix → {path}")

    def export(self, models, scaler, preprocessor, feature_cols,
               X_train, task='binary'):
        """Save models, scaler, label encoders, and feature metadata."""
        for name, model in models.items():
            p = os.path.join(self.output_dir, f'{task}_{name}_model.joblib')
            joblib.dump(model, p)

        joblib.dump(scaler,
                    os.path.join(self.output_dir, f'{task}_scaler.joblib'))
        joblib.dump(preprocessor.label_encoders,
                    os.path.join(self.output_dir, 'label_encoders.joblib'))

        # ── Feature metadata (CRITICAL for predict_depression.py) ────────────
        feature_means = {
            col: float(X_train[col].mean()) if col in X_train.columns else 0.0
            for col in feature_cols
        }
        meta = {'feature_cols': feature_cols, 'feature_means': feature_means}
        with open(os.path.join(self.output_dir, 'feature_metadata.json'), 'w') as f:
            json.dump(meta, f, indent=2)

        print(f"  Models, scaler, encoders and feature_metadata.json → {self.output_dir}/")


