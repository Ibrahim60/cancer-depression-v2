"""Table export: every catalogued CSV table -> one Word file with numbered captions.

thesis_outputs/tables/thesis_tables.docx uses an academic three-line layout
(top rule, header rule, bottom rule), captions above ("Table 4.1: ...") and
notes below. Tables with many columns are placed in landscape sections.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

import pandas as pd

from . import catalog
from .utils import Paths, get_logger


def _set_cell_border(cell, **edges) -> None:
    """edges: top/bottom/left/right = dict(sz=8, val='single', color='000000')."""
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    tcPr = cell._tc.get_or_add_tcPr()
    borders = tcPr.find(qn("w:tcBorders"))
    if borders is None:
        borders = OxmlElement("w:tcBorders")
        tcPr.append(borders)
    for edge, attrs in edges.items():
        el = borders.find(qn(f"w:{edge}"))
        if el is None:
            el = OxmlElement(f"w:{edge}")
            borders.append(el)
        for k, v in attrs.items():
            el.set(qn(f"w:{k}"), str(v))


def _no_table_borders(table) -> None:
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    tblPr = table._tbl.tblPr
    b = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        e = OxmlElement(f"w:{edge}")
        e.set(qn("w:val"), "nil")
        b.append(e)
    tblPr.append(b)


def _add_table(doc, df: pd.DataFrame, font_pt: float) -> None:
    from docx.shared import Pt
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    df = df.fillna("")
    t = doc.add_table(rows=1, cols=len(df.columns))
    _no_table_borders(t)
    rule = {"sz": 8, "val": "single", "color": "000000"}
    thin = {"sz": 4, "val": "single", "color": "000000"}
    for j, col in enumerate(df.columns):
        c = t.rows[0].cells[j]
        c.text = ""
        run = c.paragraphs[0].add_run(str(col))
        run.bold = True
        run.font.size = Pt(font_pt)
        _set_cell_border(c, top=rule, bottom=thin)
    for i, (_, row) in enumerate(df.iterrows()):
        cells = t.add_row().cells
        for j, v in enumerate(row):
            cells[j].text = ""
            p = cells[j].paragraphs[0]
            r = p.add_run(str(v))
            r.font.size = Pt(font_pt)
            if j > 0 and isinstance(v, (int, float)):
                p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
            if i == len(df) - 1:
                _set_cell_border(cells[j], bottom=rule)
    for row in t.rows:
        for c in row.cells:
            for p in c.paragraphs:
                p.paragraph_format.space_after = Pt(0)
                p.paragraph_format.space_before = Pt(0)


def build_docx(cfg: dict[str, Any], paths: Paths) -> Path:
    """Compile all catalogued tables that exist into thesis_tables.docx."""
    from docx import Document
    from docx.enum.section import WD_ORIENT
    from docx.shared import Cm, Pt
    log = get_logger()
    doc = Document()
    st = doc.styles["Normal"]
    st.font.name = "Times New Roman"
    st.font.size = Pt(11)
    sec = doc.sections[0]
    sec.page_width, sec.page_height = Cm(21.0), Cm(29.7)
    for s in doc.sections:
        s.left_margin = s.right_margin = Cm(2.5)
    doc.add_heading("Thesis tables", level=1)
    doc.add_paragraph("Generated by thesis_analysis (python -m thesis_analysis.run_all --stage report). "
                      "Every value is computed by the analysis code; do not edit numbers by hand — re-run the "
                      "pipeline instead.")
    reg = catalog.numbered(catalog.TABLES, cfg["run_subsets"], "tab")
    n_added = 0
    landscape = False
    for key, meta in reg.items():
        csv = paths.tables / f"{meta['name']}.csv"
        if not csv.exists():
            continue
        df = pd.read_csv(csv, encoding="utf-8-sig", dtype=str).fillna("")
        wide = len(df.columns) > 8
        if wide != landscape:
            new = doc.add_section()
            new.orientation = WD_ORIENT.LANDSCAPE if wide else WD_ORIENT.PORTRAIT
            w, h = (Cm(29.7), Cm(21.0)) if wide else (Cm(21.0), Cm(29.7))
            new.page_width, new.page_height = w, h
            new.left_margin = new.right_margin = Cm(2.0 if wide else 2.5)
            landscape = wide
        sub = next((s for s in cfg["run_subsets"] if key.endswith(f"_{s}")), None)
        caption = meta["caption"].rstrip(".")
        if sub:
            caption += f" ({catalog.subset_label(cfg, sub)})"
        p = doc.add_paragraph()
        r = p.add_run(f"Table {meta['number']}: ")
        r.bold = True
        p.add_run(caption + ".")
        p.paragraph_format.keep_with_next = True
        font = 9 if len(df.columns) <= 6 else (8 if len(df.columns) <= 10 else 7)
        _add_table(doc, df, font)
        note = paths.tables / f"{meta['name']}.note.txt"
        if note.exists():
            q = doc.add_paragraph()
            rr = q.add_run("Note. " + note.read_text(encoding="utf-8"))
            rr.italic = True
            rr.font.size = Pt(9)
        doc.add_paragraph()
        n_added += 1
    out = paths.tables / "thesis_tables.docx"
    doc.save(out)
    log.info("Word tables: %d tables -> %s", n_added, out)
    return out
